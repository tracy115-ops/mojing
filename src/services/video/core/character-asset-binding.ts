import type { CharacterAnchor } from '@/types/video';

/**
 * A turnaround is a derived asset. It is safe to reuse only when its source
 * portrait is still the portrait currently bound to the character.
 *
 * Legacy records have no source marker. When both assets exist, use the
 * current portrait conservatively instead of trusting an unknown old sheet.
 */
export function hasCurrentTurnaround(
  character: Pick<CharacterAnchor, 'portraitImage' | 'turnaroundImage' | 'turnaroundSourcePortrait'>,
): boolean {
  if (!character.turnaroundImage) return false;
  if (!character.portraitImage) return true;
  return character.turnaroundSourcePortrait === character.portraitImage;
}

/**
 * Resolve the single identity image that downstream generation should use.
 * Turnarounds are derived inspection assets, so they are only a fallback when
 * no single-view portrait is available.
 */
export function resolveCharacterReferenceImage(
  character: Pick<CharacterAnchor, 'portraitImage' | 'turnaroundImage' | 'turnaroundSourcePortrait' | 'costumeVariants'>,
  variantId?: string,
): { imageUrl: string; source: 'variant' | 'portrait' | 'turnaround' } | undefined {
  const variant = variantId
    ? character.costumeVariants?.find((candidate) => candidate.id === variantId)
    : undefined;
  if (variant?.portraitImage) return { imageUrl: variant.portraitImage, source: 'variant' };
  if (character.portraitImage) return { imageUrl: character.portraitImage, source: 'portrait' };
  if (hasCurrentTurnaround(character)) {
    return { imageUrl: character.turnaroundImage!, source: 'turnaround' };
  }
  return undefined;
}

/** Explicitly stale derived assets should be regenerated by the anchor stage. */
export function needsTurnaroundGeneration(
  character: Pick<CharacterAnchor, 'portraitImage' | 'turnaroundImage' | 'turnaroundSourcePortrait'>,
): boolean {
  if (!character.portraitImage || !character.turnaroundImage) return true;
  return !!character.turnaroundSourcePortrait
    && character.turnaroundSourcePortrait !== character.portraitImage;
}
